# --------------------------------------------------------------------------
# donor invariant: a failed clip does not count as used
# (test_failed_clip_does_not_count_as_used)
# --------------------------------------------------------------------------
def test_failed_clip_does_not_count_as_used():
    pool = _clips([(f"clip-{i}", "room") for i in range(3)])
    usage: dict[str, int] = {}
    first_alloc = next_allocation(pool, usage, 0, 2)
    assert first_alloc.source_ids == ["clip-0", "clip-1"]
    # clip-0's render died: only the clip that landed is committed, exactly as
    # the donor appends to used_video_paths on success only.
    usage = record_usage(usage, ["clip-1"])
    second = next_allocation(pool, usage, 1, 2)
    assert second.source_ids == ["clip-0", "clip-2"]
    assert second.reused_sources == ["clip-2"] or second.reused_sources == []
    assert usage == {"clip-1": 1}


def test_a_failed_clip_still_leaves_the_slot_to_be_filled():
    """The walk continues past a dead clip instead of costing the output a shot."""
    pool = _clips([(f"clip-{i}", "room") for i in range(3)])
    picked, landed = _render(order_clips(pool, {}), 2, failing={"clip-0"})
    assert [c.source_id for c in picked] == ["clip-0", "clip-1"]
    assert [c.source_id for c in landed] == ["clip-1"]


