def test_a_failed_fetch_does_not_spend_the_source(tmp_path, monkeypatch):
    """The donor's failure invariant, through the real selection path.

    cand-0 dies on its first download, exactly like the donor's one-shot
    ``OSError``. The scene walks past it to cand-1, and because the failure was
    never committed, the next scene is offered cand-0 again with a fresh
    ``uses_before`` of 0.
    """
    _no_llm(monkeypatch)
    monkeypatch.chdir(tmp_path)
    plan = broll_mod.plan_scenes("save money", ["budget"], 8, "ws-alloc")
    attempts: list[str] = []

    def flaky(vid, ws, aspect="9:16"):
        attempts.append(vid)
        if vid == "cand-0" and len(attempts) == 1:
            raise BrollError("clip download failed")
        return f"data/videos/{ws}/broll/{vid}.mp4"

    monkeypatch.setattr(broll_mod, "search_stock",
                        lambda q, per_page=4, orientation="portrait": _catalog(2))
    monkeypatch.setattr(broll_mod, "fetch_stock_clip", flaky)
    resolved = broll_mod.select_stock_clips(plan, "ws-alloc", source_usage={})
    used = [s for s in resolved if s.source == "stock"]
    # cand-1 (the survivor) then cand-0, cand-0, then cand-1 again — the tail
    # re-uses cand-1 because it is the least spent of the two, which is the
    # point: reuse is the fallback, not the first choice.
    assert [s.performance_json["material"]["clip_id"] for s in used] == [
        "cand-1", "cand-0", "cand-0", "cand-1"]
    # The proof: cand-0's first (failed) use left no trace in the counter.
    assert used[1].performance_json["material"]["uses_before"] == 0
    assert used[1].performance_json["material"]["reused"] is False
    assert attempts[0] == "cand-0" and attempts[1] == "cand-1"


