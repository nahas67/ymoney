def test_new_sources_are_used_before_exhausted_ones():
    pool = _clips([(f"clip-{i}", "room") for i in range(6)], duration=12.0)
    usage: dict[str, int] = {}
    selected: list[str] = []
    for index in range(3):
        picked, landed = _render(order_clips(pool, usage), 2)
        selected.extend(c.source_id for c in picked)
        usage = record_usage(usage, [c.source_id for c in landed])
    assert len(selected) == len(set(selected)) == 6
    assert selected == [f"clip-{i}" for i in range(6)]
    assert max(usage.values()) == 1


