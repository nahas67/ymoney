def test_ties_keep_the_callers_order():
    """Determinism is a product requirement, so the sort must be stable."""
    pool = _clips([("b", "room"), ("a", "room"), ("c", "room")])
    assert [c.source_id for c in order_clips(pool, {})] == ["b", "a", "c"]
    assert [c.source_id for c in order_clips(pool, {"b": 1, "a": 1})] == ["c", "b", "a"]


# --------------------------------------------------------------------------
# donor invariant: shortage reuses only exhausted keyword candidates
# (test_shortage_reuses_only_exhausted_keyword_candidates)
# --------------------------------------------------------------------------
def test_shortage_reuses_only_exhausted_keyword_candidates():
    pool = _clips([("room-0", "room"), ("window", "window"),
                   ("room-1", "room"), ("room-2", "room")])
    usage: dict[str, int] = {}
    selections: list[list[str]] = []
    reuse: list[list[str]] = []
    for index in range(3):
        alloc = next_allocation(pool, usage, index, 2)
        selections.append(alloc.source_ids)
        reuse.append(alloc.reused_sources)
        usage = record_usage(usage, alloc.source_ids)
    assert selections == [
        ["room-0", "window"], ["room-1", "window"], ["room-2", "window"]]
    # Only `window` — the group with a single candidate — was ever exhausted.
    assert reuse == [[], ["window"], ["window"]]
    assert usage == {"room-0": 1, "room-1": 1, "room-2": 1, "window": 3}


