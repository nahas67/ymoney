def _clips(spec: list[tuple[str, str]], duration: float = 6.0) -> list[Clip]:
    """``[(source_id, group), ...]`` -> a materialized pool."""
    return [Clip(source_id=sid, group=group, duration=duration) for sid, group in spec]


def _render(ordered: list[Clip], count: int, failing: set[str] | None = None
            ) -> tuple[list[Clip], list[Clip]]:
    """What a renderer does: walk the ordered pool, fill ``count`` slots.

    A clip in ``failing`` is attempted and dies. It consumes no slot (the
    output still needs its footage) and it is not reported as landed, so the
    caller will not commit it to usage.
    """
    bad = failing or set()
    picked: list[Clip] = []
    landed: list[Clip] = []
    for clip in ordered:
        if len(picked) >= count:
            break
        picked.append(clip)
        if clip.source_id not in bad:
            landed.append(clip)
    return picked, landed


# --------------------------------------------------------------------------
# donor invariant: matched batch rotates candidates in keyword order
# (test_matched_batch_rotates_candidates_in_keyword_order)
# --------------------------------------------------------------------------
def test_round_robin_across_keyword_groups_in_keyword_order():
    pool = _clips([(f"room-{i}", "room") for i in range(3)]
                  + [(f"window-{i}", "window") for i in range(3)])
    usage: dict[str, int] = {}
    selections = []
    for index in range(3):
        picked, landed = _render(order_clips(pool, usage), 2)
        selections.append([c.source_id for c in picked])
        usage = record_usage(usage, [c.source_id for c in landed])
    assert selections == [
        ["room-0", "window-0"], ["room-1", "window-1"], ["room-2", "window-2"]]
    # Nothing was spent twice, so nothing is reported as reuse.
    assert set(usage.values()) == {1}


